using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System.Linq;
using System.Text;

namespace NOF.Hosting.AspNetCore.SourceGenerator;
/// <summary>Retains request lambda types for MapGet&lt;Operation&gt; without analyzing binding or output function bodies.</summary>
[Generator]
public sealed class OperationRequestBindingGenerator : IIncrementalGenerator
{
    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var maps = context.SyntaxProvider.CreateSyntaxProvider(static (node, _) => node is GenericNameSyntax { TypeArgumentList.Arguments.Count: 1 } name && (name.Identifier.ValueText is "MapGet" or "MapPost" or "MapPut" or "MapPatch" or "MapDelete" or "MapOperation"), static (syntax, _) => Describe(syntax)).Where(static item => item is not null).Collect();
        context.RegisterSourceOutput(maps.Combine(context.CompilationProvider.Select(static (compilation, _) => compilation.AssemblyName ?? "Application")), static (output, values) =>
        {
            var assembly = new string(values.Right.Select(character => char.IsLetterOrDigit(character) ? character : '_').ToArray());
            var code = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace NOF.Hosting.AspNetCore;\n");
            code.Append("/// <summary>Statically typed request configuration for this assembly's operation routes.</summary>\npublic static class __HttpOperationRequests_").Append(assembly).AppendLine("\n{");
            foreach (var item in values.Left.Distinct().Where(item => item is not null))
            {
                var parts = item!.Split('|');
                var target = "global::NOF.Hosting.AspNetCore.HttpOperationEndpointBuilder<" + parts[0] + ">";
                code.AppendLine("    /// <summary>Configures the selected operation's exact request type.</summary>");
                code.Append("    public static ").Append(target).Append(" Request(this ").Append(target).Append(" builder, global::System.Action<global::NOF.Hosting.AspNetCore.HttpRequestBuilder<").Append(parts[1]).AppendLine(">> configure)\n    {");
                code.Append("        var request = new global::NOF.Hosting.AspNetCore.HttpRequestBuilder<").Append(parts[1]).AppendLine(">();\n        configure(request);\n        builder.Add(endpoint => endpoint.Metadata.Add(request));\n        return builder;\n    }");
            }

            code.AppendLine("}");
            output.AddSource("OperationRequests.g.cs", SourceText.From(code.ToString(), Encoding.UTF8));
        });
    }

    private static string? Describe(GeneratorSyntaxContext context)
    {
        var name = (GenericNameSyntax)context.Node;
        var argument = name.TypeArgumentList.Arguments[0];
        var symbol = context.SemanticModel.GetTypeInfo(argument).Type as INamedTypeSymbol;
        for (var current = symbol; current is not null; current = current.BaseType)
        {
            if (current.OriginalDefinition.ToDisplayString() == "NOF.Application.ServiceOperation<TRequest, TResponse>")
            {
                return symbol!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "|" + current.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            }
        }

        // Application operation bases may be generated in this same compilation. Use only original service declarations.
        if (argument is IdentifierNameSyntax identifier)
        {
            argument = argument.SyntaxTree.GetRoot().DescendantNodes().OfType<UsingDirectiveSyntax>().FirstOrDefault(usingDirective => usingDirective.Alias?.Name.Identifier.ValueText == identifier.Identifier.ValueText)?.Name ?? argument;
        }

        if (argument is not QualifiedNameSyntax qualified)
        {
            return null;
        }

        var container = context.SemanticModel.GetSymbolInfo(qualified.Left).Symbol as INamedTypeSymbol;
        for (var current = container; current is not null; current = current.BaseType)
        {
            if (current.OriginalDefinition.ToDisplayString() != "NOF.Application.ApplicationService<TService>")
            {
                continue;
            }

            var contract = (INamedTypeSymbol)current.TypeArguments[0];
            var method = new[]
            {
                contract
            }.Concat(contract.AllInterfaces).SelectMany(type => type.GetMembers(qualified.Right.Identifier.ValueText)).OfType<IMethodSymbol>().FirstOrDefault();
            if (method?.Parameters.Length != 1)
            {
                return null;
            }

            return container!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "." + qualified.Right.Identifier.ValueText + "|" + method.Parameters[0].Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        }

        return null;
    }
}
