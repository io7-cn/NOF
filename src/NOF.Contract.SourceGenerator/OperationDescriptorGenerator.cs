using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using NOF.SourceGeneration;
using System.Linq;
using System.Text;

namespace NOF.Contract.SourceGenerator;

/// <summary>Generates transport-independent operation references alongside unmodified service contracts.</summary>
[Generator]
public sealed class OperationDescriptorGenerator : IIncrementalGenerator
{
    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var contracts = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is InterfaceDeclarationSyntax,
            static (syntax, _) => syntax.SemanticModel.GetDeclaredSymbol(syntax.Node) as INamedTypeSymbol)
            .Where(static symbol => symbol is { ContainingType: null, Arity: 0 }
                && symbol.AllInterfaces.Any(type => type.ToDisplayString() == "NOF.Contract.IApplicationService")).Collect();
        context.RegisterSourceOutput(contracts, static (output, symbols) =>
        {
            foreach (var contract in symbols.Distinct(SymbolEqualityComparer.Default).OfType<INamedTypeSymbol>())
            {
                var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
                if (!contract.ContainingNamespace.IsGlobalNamespace)
                {
                    source.Append("namespace ").Append(contract.ContainingNamespace.ToDisplayString()).AppendLine(";");
                }
                source.AppendLine("/// <summary>Contract operation identities usable without referencing consumer implementations.</summary>");
                source.Append("public static class ").Append(contract.Name).AppendLine("Operations\n{");
                foreach (var method in contract.GetMembers().OfType<IMethodSymbol>().Where(method => method.MethodKind == MethodKind.Ordinary
                    && !method.IsStatic && !method.ReturnsVoid && method.Arity == 0 && method.Parameters.Length == 1))
                {
                    source.AppendLine("    /// <summary>Gets the canonical typed operation reference.</summary>");
                    source.Append("    public static global::NOF.Contract.ServiceOperationDescriptor<")
                        .Append(method.Parameters[0].Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).Append(", ")
                        .Append(ExpectedFailureModel.ResponseTypeName(method)).Append("> @").Append(method.Name)
                        .Append(" { get; } = new(typeof(").Append(contract.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
                        .Append("), ").Append(Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(method.Name, true))
                        .Append(", allowsNullResponse: ").Append(ExpectedFailureModel.AllowsNull(method) ? "true" : "false").AppendLine(");");
                }
                source.AppendLine("}");
                output.AddSource(contract.ToDisplayString().Replace('.', '_') + ".Operations.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
            }
        });
    }
}
