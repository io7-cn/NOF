using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using NOF.Internal;
using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

namespace NOF.Contract.SourceGenerator;

[Generator]
public sealed class HttpRpcClientGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var interfaceProvider = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is InterfaceDeclarationSyntax,
                static (ctx, _) =>
                {
                    if (ctx.SemanticModel.GetDeclaredSymbol(ctx.Node) is not INamedTypeSymbol interfaceSymbol
                        || !ApplicationServiceHelpers.IsApplicationServiceInterface(interfaceSymbol)
                        || interfaceSymbol.ToDisplayString() == ApplicationServiceHelpers.ApplicationServiceInterfaceFqn
                        || !ApplicationServiceHelpers.TryGetHttpTransport(interfaceSymbol, out var _transport))
                    {
                        return null;
                    }

                    return interfaceSymbol;
                })
            .Where(static symbol => symbol is not null);

        context.RegisterSourceOutput(interfaceProvider.Collect(), Generate);
    }

    private static void Generate(SourceProductionContext context, ImmutableArray<INamedTypeSymbol?> interfaces)
    {
        foreach (var serviceInterface in interfaces.Distinct(SymbolEqualityComparer.Default).OfType<INamedTypeSymbol>())
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            GenerateForInterface(context, serviceInterface);
        }
    }

    private static void GenerateForInterface(SourceProductionContext context, INamedTypeSymbol serviceInterface)
    {
        if (!ApplicationServiceHelpers.TryGetHttpTransport(serviceInterface, out var transport))
        {
            return;
        }

        var methods = GetServiceMethods(serviceInterface);
        if (methods.Count == 0)
        {
            return;
        }

        var targetNamespace = ApplicationServiceHelpers.GetFullNamespace(serviceInterface.ContainingNamespace);
        var typeParameters = ApplicationServiceHelpers.GetTypeParameterList(serviceInterface.TypeParameters);
        var clientName = ApplicationServiceHelpers.GetHttpClientName(serviceInterface.Name) + typeParameters;
        var clientInterfaceName = ApplicationServiceHelpers.GetClientInterfaceName(serviceInterface.Name) + typeParameters;
        var routedMethods = methods.Select(method => GetRouteBinding(method, transport)).ToArray();
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System.Text.Json;");
        sb.AppendLine();
        for (var i = 0; i < routedMethods.Length; i++)
        {
            if (routedMethods[i] is not null)
            {
                var qualifiedClient = string.IsNullOrEmpty(targetNamespace) ? clientName : $"{targetNamespace}.{clientName}";
                sb.AppendLine($"[assembly: global::NOF.Contract.GeneratedHttpRpcRouteAttribute<global::{qualifiedClient}.{HttpRpcRouteEmitter.GetName(methods[i], i)}>]");
            }
        }
        if (!string.IsNullOrWhiteSpace(targetNamespace))
        {
            sb.AppendLine($"namespace {targetNamespace}");
            sb.AppendLine("{");
        }

        sb.AppendLine($"    public partial class {clientName} : {clientInterfaceName}");
        ApplicationServiceHelpers.AppendTypeParameterConstraints(sb, serviceInterface, 1);
        sb.AppendLine("    {");
        sb.AppendLine("        private readonly global::System.Net.Http.HttpClient _httpClient;");
        sb.AppendLine("        private readonly global::NOF.Contract.IRequestOutboundPipelineExecutor? _outboundPipeline;");
        sb.AppendLine("        private static readonly global::System.Text.Json.JsonSerializerOptions _jsonOptions = global::System.Text.Json.JsonSerializerOptions.NOF;");
        sb.AppendLine();
        for (var i = 0; i < methods.Count; i++)
        {
            EmitMethodInfoField(sb, methods[i], i);
        }

        sb.AppendLine();
        sb.AppendLine($"        public {ApplicationServiceHelpers.GetHttpClientName(serviceInterface.Name)}(global::System.Net.Http.HttpClient httpClient, global::NOF.Contract.IRequestOutboundPipelineExecutor? outboundPipeline = null)");
        sb.AppendLine("        {");
        sb.AppendLine("            global::System.ArgumentNullException.ThrowIfNull(httpClient);");
        sb.AppendLine("            _httpClient = httpClient;");
        sb.AppendLine("            _outboundPipeline = outboundPipeline;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        private static global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<T> GetJsonTypeInfo<T>()");
        sb.AppendLine("            => _jsonOptions.GetRequiredTypeInfo<T>();");
        sb.AppendLine();

        if (routedMethods.Any(static binding => binding is not null))
        {
            HttpRpcRouteEmitter.EmitClientPathEncoder(sb);
        }

        for (var i = 0; i < methods.Count; i++)
        {
            var method = methods[i];
            var binding = routedMethods[i];
            var codec = HttpRpcRouteEmitter.GetName(method, i);
            EmitHttpMethodBody(sb, method, transport, GetMethodInfoFieldName(method, i), binding, codec);
            if (binding is not null)
            {
                var endpoint = ApplicationServiceHelpers.ExtractEndpointInfo(method);
                var relativeRoute = BuildRoute(transport.RoutePrefix, endpoint.Route!);
                HttpRpcRouteEmitter.Emit(sb, method, endpoint, binding, codec, relativeRoute.Substring(1));
            }
        }

        sb.AppendLine("    }");
        if (!string.IsNullOrWhiteSpace(targetNamespace))
        {
            sb.AppendLine("}");
        }

        context.AddSource(GetHintName(serviceInterface, "HttpRpcClient"), SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static HttpRpcRouteBinding? GetRouteBinding(ServiceMethodInfo method, HttpTransportInfo transport)
    {
        if (transport.Style == HttpRpcStyle.ControllerRpc)
        {
            var endpoint = ApplicationServiceHelpers.ExtractEndpointInfo(method);
            if (endpoint.Route is { } route && ApplicationServiceHelpers.ContainsRouteParameters(route))
            {
                return HttpRpcRouteBinding.Create(method.Method, method.RequestType!, endpoint.Method, route, out _);
            }
        }

        return null;
    }

    private static List<ServiceMethodInfo> GetServiceMethods(INamedTypeSymbol serviceInterface)
    {
        var methods = new List<ServiceMethodInfo>();
        foreach (var member in serviceInterface.GetMembers())
        {
            if (member is not IMethodSymbol { MethodKind: MethodKind.Ordinary } method
                || method.IsImplicitlyDeclared
                || !ApplicationServiceHelpers.TryGetRequestParameter(method, out var requestParameter)
                || requestParameter?.Type is not INamedTypeSymbol requestType
                || !ApplicationServiceHelpers.TryGetServiceReturnInfo(method, out var returnInfo))
            {
                continue;
            }

            methods.Add(new ServiceMethodInfo
            {
                Method = method,
                RequestType = requestType,
                ReturnInfo = returnInfo,
                OperationName = method.Name
            });
        }

        return methods;
    }

    private static void EmitMethodInfoField(StringBuilder sb, ServiceMethodInfo method, int index)
    {
        var serviceTypeName = method.Method.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var parameterTypes = method.Method.Parameters
            .Select(static parameter => $"typeof({parameter.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)})")
            .ToArray();
        var parameterTypesExpression = parameterTypes.Length == 0
            ? "global::System.Type.EmptyTypes"
            : $"[{string.Join(", ", parameterTypes)}]";
        var fieldName = GetMethodInfoFieldName(method, index);

        sb.AppendLine($"        private static readonly global::System.Reflection.MethodInfo {fieldName} =");
        sb.AppendLine($"            typeof({serviceTypeName}).GetMethod(nameof({serviceTypeName}.{method.Method.Name}), {parameterTypesExpression})");
        sb.AppendLine($"            ?? throw new global::System.InvalidOperationException(\"Unable to resolve method '{serviceTypeName}.{method.Method.Name}'.\");");
    }

    private static void EmitHttpMethodBody(
        StringBuilder sb,
        ServiceMethodInfo method,
        HttpTransportInfo transport,
        string methodInfoFieldName,
        HttpRpcRouteBinding? binding,
        string codec)
    {
        var endpoint = ApplicationServiceHelpers.ExtractEndpointInfo(method);
        var requestType = endpoint.RequestType!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var responseType = endpoint.ReturnInfo.ClientResponseTypeDisplay;
        var serviceType = method.Method.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var isStreaming = endpoint.ReturnInfo.IsStream;
        var streamItemType = endpoint.ReturnInfo.StreamItemType?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        sb.AppendLine($"        public virtual async {endpoint.ReturnInfo.ClientTaskReturnTypeDisplay} {method.Method.Name}Async({requestType} request, global::NOF.Contract.Context context, global::System.Threading.CancellationToken cancellationToken = default)");
        sb.AppendLine("        {");
        sb.AppendLine("            global::System.ArgumentNullException.ThrowIfNull(request);");
        sb.AppendLine("            global::System.ArgumentNullException.ThrowIfNull(context);");
        sb.AppendLine("            var outboundContext = new global::NOF.Contract.RequestOutboundContext(context)");
        sb.AppendLine("            {");
        sb.AppendLine($"                ServiceType = typeof({serviceType}),");
        sb.AppendLine($"                MethodInfo = {methodInfoFieldName}");
        sb.AppendLine("            };");
        sb.AppendLine($"            {responseType} result = default!;");
        sb.AppendLine("            global::NOF.Contract.RequestOutboundHandlerDelegate dispatch = async (currentContext, currentRequest, ct) =>");
        sb.AppendLine("            {");

        if (transport.Style == HttpRpcStyle.JsonRpc)
        {
            var jsonRpcRoute = MakeBaseAddressRelative(NormalizeRoutePrefix(transport.RoutePrefix));
            if (isStreaming)
            {
                sb.AppendLine($"                result = await global::NOF.Contract.JsonRpcHttpClient.SendStreaming{(endpoint.ReturnInfo.HasSuccessWrapper ? "WithMessage" : "")}Async<{requestType}, {streamItemType}>(");
            }
            else
            {
                sb.AppendLine($"                result = await global::NOF.Contract.JsonRpcHttpClient.Send{(ApplicationServiceHelpers.ImplementsResultContract(method.Method.ReturnType) ? "" : "Value")}Async<{requestType}, {responseType}>(");
            }

            sb.AppendLine("                    _httpClient,");
            sb.AppendLine($"                    {Literal(jsonRpcRoute)},");
            sb.AppendLine($"                    nameof({serviceType}.{method.Method.Name}),");
            sb.AppendLine($"                    ({requestType})currentRequest,");
            sb.AppendLine("                    currentContext.Headers,");
            sb.AppendLine($"                    GetJsonTypeInfo<{requestType}>(),");
            if (isStreaming)
            {
                sb.AppendLine($"                    GetJsonTypeInfo<{streamItemType}>(),");
                sb.AppendLine("                    GetJsonTypeInfo<global::NOF.Contract.Result>(),");
            }
            else
            {
                sb.AppendLine($"                    GetJsonTypeInfo<{responseType}>(),");
            }

            var nullableValueResponse = !isStreaming && !ApplicationServiceHelpers.ImplementsResultContract(method.Method.ReturnType)
                && (method.Method.ReturnType.NullableAnnotation == NullableAnnotation.Annotated
                    || method.Method.ReturnType is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T });
            sb.AppendLine($"                    ct{(nullableValueResponse ? ", allowNull: true" : "")}).ConfigureAwait(false);");
        }
        else
        {
            EmitControllerRpcDispatch(sb, endpoint, transport.RoutePrefix, requestType, responseType, isStreaming, streamItemType, binding, codec);
        }

        sb.AppendLine("                currentContext.Response = result;");
        sb.AppendLine("            };");
        sb.AppendLine();
        sb.AppendLine("            if (_outboundPipeline is null)");
        sb.AppendLine("            {");
        sb.AppendLine("                await dispatch(outboundContext, request, cancellationToken).ConfigureAwait(false);");
        sb.AppendLine("            }");
        sb.AppendLine("            else");
        sb.AppendLine("            {");
        sb.AppendLine("                await _outboundPipeline.ExecuteAsync(outboundContext, request, dispatch, cancellationToken).ConfigureAwait(false);");
        sb.AppendLine("            }");
        sb.AppendLine();
        var failureFactory = ApplicationServiceHelpers.ImplementsResultContract(method.Method.ReturnType)
            ? $"static failure => {responseType}.CreateFailure(failure), " : string.Empty;
        var allowNull = method.Method.ReturnType.NullableAnnotation == NullableAnnotation.Annotated
            || method.Method.ReturnType is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T };
        sb.AppendLine($"            return outboundContext.Execution.Require<{responseType}>({failureFactory}allowNull: {(allowNull ? "true" : "false")});");
        sb.AppendLine("        }");
        sb.AppendLine();
    }

    private static void EmitControllerRpcDispatch(
        StringBuilder sb,
        EndpointInfo endpoint,
        string? routePrefix,
        string requestType,
        string responseType,
        bool isStreaming,
        string? streamItemType,
        HttpRpcRouteBinding? binding,
        string codec)
    {
        var route = BuildRoute(routePrefix, endpoint.Route ?? endpoint.OperationName);
        var httpMethod = GetHttpMethod(endpoint.Method);
        var uri = binding is null ? Literal(route) : HttpRpcRouteEmitter.BuildClientUri(route, binding, requestType);
        sb.AppendLine($"                var endpoint = {uri};");
        if (IsBodyMethod(endpoint.Method))
        {
            sb.AppendLine($"                using var httpRequest = new global::System.Net.Http.HttpRequestMessage(global::System.Net.Http.{httpMethod}, endpoint);");
            if (binding is null)
            {
                sb.AppendLine($"                httpRequest.Content = global::System.Net.Http.Json.JsonContent.Create(({requestType})currentRequest, GetJsonTypeInfo<{requestType}>());");
            }
            else if (binding.HasBody)
            {
                sb.AppendLine($"                httpRequest.Content = {codec}.CreateBody(({requestType})currentRequest, _jsonOptions);");
            }
        }
        else
        {
            var properties = binding?.Remaining ?? ApplicationServiceHelpers.GetAllPublicProperties(endpoint.RequestType!);
            if (properties.Count > 0)
            {
                sb.AppendLine("                var queryParts = new global::System.Collections.Generic.List<string>();");
                for (var i = 0; i < properties.Count; i++)
                {
                    EmitQueryParamAppend(sb, properties[i], requestType, i, binding is not null);
                }

                sb.AppendLine("                if (queryParts.Count > 0)");
                sb.AppendLine("                {");
                sb.AppendLine("                    endpoint = endpoint + \"?\" + string.Join(\"&\", queryParts);");
                sb.AppendLine("                }");
            }

            sb.AppendLine($"                using var httpRequest = new global::System.Net.Http.HttpRequestMessage(global::System.Net.Http.{httpMethod}, endpoint);");
        }

        if (isStreaming)
        {
            sb.AppendLine("                httpRequest.Headers.Accept.Add(new global::System.Net.Http.Headers.MediaTypeWithQualityHeaderValue(\"text/event-stream\"));");
        }

        sb.AppendLine("                foreach (var (name, value) in currentContext.Headers)");
        sb.AppendLine("                {");
        sb.AppendLine("                    if (value is not null)");
        sb.AppendLine("                    {");
        sb.AppendLine("                        httpRequest.Headers.Remove(name);");
        sb.AppendLine("                        httpRequest.Headers.TryAddWithoutValidation(name, value);");
        sb.AppendLine("                    }");
        sb.AppendLine("                }");

        if (isStreaming)
        {
            sb.AppendLine("                var response = await _httpClient.SendAsync(httpRequest, global::System.Net.Http.HttpCompletionOption.ResponseHeadersRead, ct).ConfigureAwait(false);");
            sb.AppendLine("                if (!response.IsSuccessStatusCode)");
            sb.AppendLine("                {");
            sb.AppendLine("                    using (response)");
            sb.AppendLine("                    {");
            sb.AppendLine($"                    result = await global::NOF.Contract.HttpRpcTransportResultReader.ReadFailureAsync<{responseType}>(response, ct).ConfigureAwait(false);");
            sb.AppendLine("                    }");
            sb.AppendLine("                }");
            sb.AppendLine("                else if (string.Equals(response.Content.Headers.ContentType?.MediaType, \"text/event-stream\", global::System.StringComparison.OrdinalIgnoreCase))");
            sb.AppendLine("                {");
            sb.AppendLine($"                    var stream = global::NOF.Contract.SseResponseReader.ReadAsync<{streamItemType}>(response, GetJsonTypeInfo<{streamItemType}>(), ct);");
            sb.AppendLine(endpoint.ReturnInfo.HasSuccessWrapper
                ? $"                    result = global::NOF.Contract.Result.WithMessage<global::System.Collections.Generic.IAsyncEnumerable<{streamItemType}>>(stream, global::NOF.Contract.StreamingResponseMetadata.ReadMessage(response));"
                : $"                    result = global::NOF.Contract.Result.Stream<{streamItemType}>(stream);");
            sb.AppendLine("                }");
            sb.AppendLine("                else");
            sb.AppendLine("                {");
            sb.AppendLine("                    using (response)");
            sb.AppendLine("                    {");
            sb.AppendLine($"                        result = global::NOF.Contract.RpcResponse.Require<{responseType}>(await global::NOF.Contract.HttpRpcTransportResultReader.ReadStreamingFallbackAsync<{streamItemType}>(response, GetJsonTypeInfo<global::NOF.Contract.Result>(), ct).ConfigureAwait(false));");
            sb.AppendLine("                    }");
            sb.AppendLine("                }");
        }
        else
        {
            sb.AppendLine("                using var response = await _httpClient.SendAsync(httpRequest, ct).ConfigureAwait(false);");
            var isOutcome = ApplicationServiceHelpers.ImplementsResultContract(endpoint.ReturnInfo.ValueType);
            var allowNull = endpoint.ReturnInfo.ValueType.NullableAnnotation == NullableAnnotation.Annotated
                || endpoint.ReturnInfo.ValueType is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T };
            sb.AppendLine($"                result = await global::NOF.Contract.HttpRpcTransportResultReader.Read{(isOutcome ? "" : "Value")}Async<{responseType}>(response, GetJsonTypeInfo<{responseType}>(), ct{(!isOutcome && allowNull ? ", allowNull: true" : "")}).ConfigureAwait(false);");
        }
    }

    private static void EmitQueryParamAppend(StringBuilder sb, IPropertySymbol property, string requestType, int index, bool invariant)
    {
        var propertyName = property.Name;
        var accessor = $"(({requestType})currentRequest).{(invariant ? "@" : "")}{propertyName}";
        var nullableValueType = property.Type as INamedTypeSymbol;
        var isNullableValueType = nullableValueType?.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;
        var isNullable = property.Type.NullableAnnotation == NullableAnnotation.Annotated
            || isNullableValueType;
        if (isNullableValueType)
        {
            var cachedValue = $"queryValue{index}";
            var unwrappedValue = $"{cachedValue}Value";
            sb.AppendLine($"                var {cachedValue} = {accessor};");
            sb.AppendLine($"                if ({cachedValue} is {{ }} {unwrappedValue})");
            sb.AppendLine("                {");
            sb.AppendLine($"                    queryParts.Add(global::System.Uri.EscapeDataString({Literal(propertyName)}) + \"=\" + global::System.Uri.EscapeDataString({FormatValueExpression(unwrappedValue, nullableValueType!.TypeArguments[0], invariant)}));");
            sb.AppendLine("                }");
        }
        else if (isNullable)
        {
            var cachedValue = $"queryValue{index}";
            sb.AppendLine($"                var {cachedValue} = {accessor};");
            sb.AppendLine($"                if ({cachedValue} is not null)");
            sb.AppendLine("                {");
            sb.AppendLine($"                    queryParts.Add(global::System.Uri.EscapeDataString({Literal(propertyName)}) + \"=\" + global::System.Uri.EscapeDataString({FormatValueExpression(cachedValue, property.Type, invariant)}));");
            sb.AppendLine("                }");
        }
        else
        {
            sb.AppendLine($"                queryParts.Add(global::System.Uri.EscapeDataString({Literal(propertyName)}) + \"=\" + global::System.Uri.EscapeDataString({FormatValueExpression(accessor, property.Type, invariant)}));");
        }
    }

    internal static string FormatValueExpression(string accessor, ITypeSymbol type, bool invariant = false)
    {
        if (type.SpecialType == SpecialType.System_String)
        {
            return accessor;
        }

        return type.ToDisplayString() switch
        {
            "System.DateTime" => $"{accessor}.ToString(\"O\", global::System.Globalization.CultureInfo.InvariantCulture)",
            "System.DateTimeOffset" => $"{accessor}.ToString(\"O\", global::System.Globalization.CultureInfo.InvariantCulture)",
            "System.DateOnly" => $"{accessor}.ToString(\"yyyy-MM-dd\", global::System.Globalization.CultureInfo.InvariantCulture)",
            "System.TimeOnly" => $"{accessor}.ToString(\"HH:mm:ss.FFFFFFF\", global::System.Globalization.CultureInfo.InvariantCulture)",
            _ when invariant => $"global::System.Convert.ToString({accessor}, global::System.Globalization.CultureInfo.InvariantCulture)!",
            _ => $"{accessor}.ToString()!"
        };
    }

    private static string GetMethodInfoFieldName(ServiceMethodInfo method, int index)
        => $"__{method.Method.Name}MethodInfo_{index}";

    private static string GetHintName(INamedTypeSymbol symbol, string suffix)
    {
        var builder = new StringBuilder(symbol.ToDisplayString().Length + suffix.Length + 5);
        foreach (var character in symbol.ToDisplayString())
        {
            builder.Append(char.IsLetterOrDigit(character) ? character : '_');
        }

        return builder.Append('.').Append(suffix).Append(".g.cs").ToString();
    }

    private static string BuildRoute(string? prefix, string route)
    {
        var normalizedPrefix = NormalizeRoutePrefix(prefix).TrimEnd('/');
        var normalizedRoute = NormalizeRoute(route);
        var combinedRoute = normalizedPrefix + normalizedRoute;

        return MakeBaseAddressRelative(combinedRoute);
    }

    private static string NormalizeRoutePrefix(string? routePrefix)
    {
        if (routePrefix is not null
            && HttpRoutePrefix.TryNormalize(routePrefix, out var normalizedRoutePrefix, out _))
        {
            return normalizedRoutePrefix;
        }

        // The analyzer reports invalid prefixes. Falling back to root keeps generation
        // deterministic and prevents malformed user input from crashing the generator.
        return "/";
    }

    private static string MakeBaseAddressRelative(string route)
    {
        var relativeRoute = route.TrimStart('/');
        return string.IsNullOrEmpty(relativeRoute) ? "./" : "./" + relativeRoute;
    }

    private static string NormalizeRoute(string route)
    {
        route = route.TrimEnd('/');
        if (string.IsNullOrEmpty(route))
        {
            return "/";
        }

        return route.StartsWith("/", StringComparison.Ordinal) ? route : "/" + route;
    }

    private static string Literal(string value)
        => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, quote: true);

    private static string GetHttpMethod(HttpVerb verb) => verb switch
    {
        HttpVerb.Get => "HttpMethod.Get",
        HttpVerb.Post => "HttpMethod.Post",
        HttpVerb.Put => "HttpMethod.Put",
        HttpVerb.Delete => "HttpMethod.Delete",
        HttpVerb.Patch => "HttpMethod.Patch",
        _ => throw new ArgumentOutOfRangeException(nameof(verb), verb, null)
    };

    private static bool IsBodyMethod(HttpVerb verb)
        => verb is HttpVerb.Post or HttpVerb.Put or HttpVerb.Patch;
}
