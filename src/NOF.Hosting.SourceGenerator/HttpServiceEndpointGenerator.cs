using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

namespace NOF.Hosting.SourceGenerator;

/// <summary>Generates only server-side HTTP route binding and serialization metadata.</summary>
[Generator]
public sealed class HttpServiceEndpointGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var contracts = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is InterfaceDeclarationSyntax,
            static (syntax, _) => syntax.SemanticModel.GetDeclaredSymbol(syntax.Node) is INamedTypeSymbol contract
                && ApplicationServiceHelpers.IsApplicationServiceContract(contract) ? contract : null)
            .Where(static contract => contract is not null);
        context.RegisterSourceOutput(contracts.Collect(), Generate);
    }

    private static void Generate(SourceProductionContext context, ImmutableArray<INamedTypeSymbol?> contracts)
    {
        foreach (var contract in contracts.Distinct(SymbolEqualityComparer.Default).OfType<INamedTypeSymbol>())
        {
            if (contract.TypeParameters.Length != 0
                || !ApplicationServiceHelpers.TryGetHttpTransport(contract, out var transport)
                || transport.Style != HttpRpcStyle.ControllerRpc)
            {
                continue;
            }
            var ns = ApplicationServiceHelpers.GetFullNamespace(contract.ContainingNamespace);
            var holder = "__NofHttpEndpoints_" + contract.Name;
            var qualified = string.IsNullOrEmpty(ns) ? "global::" + holder : "global::" + ns + "." + holder;
            var attributes = new StringBuilder();
            var body = new StringBuilder();
            var index = 0;
            foreach (var method in contract.GetMembers().OfType<IMethodSymbol>())
            {
                if (method.MethodKind != MethodKind.Ordinary || method.IsImplicitlyDeclared
                    || !ApplicationServiceHelpers.TryGetRequestParameter(method, out var parameter)
                    || parameter?.Type is not INamedTypeSymbol request
                    || !ApplicationServiceHelpers.TryGetServiceReturnInfo(method, out var response))
                {
                    continue;
                }
                var info = new ServiceMethodInfo { Method = method, RequestType = request, ReturnInfo = response, OperationName = method.Name };
                var endpoint = ApplicationServiceHelpers.ExtractEndpointInfo(info);
                var route = endpoint.Route ?? method.Name;
                if (!ApplicationServiceHelpers.ContainsRouteParameters(route))
                {
                    continue;
                }
                var binding = HttpRpcRouteBinding.Create(method, request, endpoint.Method, route, out _);
                if (binding is null)
                {
                    continue;
                }
                var name = HttpRpcRouteEmitter.GetName(info, index++);
                attributes.AppendLine($"[assembly: global::NOF.Hosting.AspNetCore.GeneratedHttpRpcRouteAttribute<{qualified}.{name}>]");
                var prefix = (transport.RoutePrefix ?? string.Empty).Trim('/');
                var template = string.IsNullOrEmpty(prefix) ? route.Trim('/') : prefix + "/" + route.Trim('/');
                HttpRpcRouteEmitter.Emit(body, info, endpoint, binding, name, template);
            }
            if (index == 0)
            {
                continue;
            }
            var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nusing System.Text.Json;\n");
            source.Append(attributes);
            if (!string.IsNullOrEmpty(ns))
            {
                source.AppendLine("namespace " + ns);
                source.AppendLine("{");
            }
            source.AppendLine("/// <summary>Contains generated server-only HTTP endpoint metadata.</summary>");
            source.AppendLine("public static class " + holder);
            source.AppendLine("{");
            source.Append(body).AppendLine("}");
            if (!string.IsNullOrEmpty(ns))
            {
                source.AppendLine("}");
            }
            var hint = new string(contract.ToDisplayString().Select(static character => char.IsLetterOrDigit(character) ? character : '_').ToArray());
            context.AddSource(hint + ".HttpEndpoints.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
        }
    }
}
