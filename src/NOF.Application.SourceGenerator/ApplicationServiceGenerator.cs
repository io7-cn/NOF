using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;
using NOF.SourceGeneration;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

namespace NOF.Application.SourceGenerator;

[Generator]
public sealed class ApplicationServiceGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax,
                static (ctx, _) =>
                {
                    if (ctx.SemanticModel.GetDeclaredSymbol(ctx.Node) is not INamedTypeSymbol classSymbol)
                    {
                        return null;
                    }

                    return ApplicationServiceSymbolHelper.TryGetServiceInterface(classSymbol, out var _) ? classSymbol : null;
                })
            .Where(static x => x is not null);

        context.RegisterSourceOutput(candidates, static (spc, symbol) =>
        {
            GenerateForClass(spc, symbol!);
        });
    }

    private static void GenerateForClass(SourceProductionContext context, INamedTypeSymbol classSymbol)
    {
        if (!ApplicationServiceSymbolHelper.TryGetServiceInterface(classSymbol, out var serviceInterface) || serviceInterface is null)
        {
            return;
        }

        var serviceMethods = serviceInterface.GetMembers().OfType<IMethodSymbol>()
            .Where(m => m.MethodKind == MethodKind.Ordinary && !m.IsImplicitlyDeclared)
            .ToList();

        if (serviceMethods.Count == 0)
        {
            return;
        }

        var ns = classSymbol.ContainingNamespace is { IsGlobalNamespace: false }
            ? classSymbol.ContainingNamespace.ToDisplayString()
            : null;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        if (!string.IsNullOrWhiteSpace(ns))
        {
            sb.AppendLine($"namespace {ns}");
            sb.AppendLine("{");
        }

        sb.AppendLine($"partial class {classSymbol.Name} : global::NOF.Application.IApplicationServiceImplementation");
        sb.AppendLine("{");

        sb.AppendLine("    private static readonly global::System.Collections.Generic.IReadOnlyDictionary<string, global::NOF.Application.ServiceOperationMapping> __rpcHandlerMappings =");
        sb.AppendLine("        new global::System.Collections.Generic.Dictionary<string, global::NOF.Application.ServiceOperationMapping>");
        sb.AppendLine("        {");

        foreach (var method in serviceMethods)
        {
            if (method.Parameters.Length != 1)
            {
                continue;
            }

            var serviceTypeName = serviceInterface.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var requestTypeName = method.Parameters[0].Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var originalReturnTypeName = ExpectedFailureModel.Declarations(method).Length > 0
                ? ExpectedFailureModel.ResultTypeName(method, classSymbol)
                : method.ReturnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            sb.AppendLine($"            [nameof({serviceTypeName}.{method.Name})] = new global::NOF.Application.ServiceOperationMapping(typeof({method.Name}), typeof({requestTypeName}), typeof({originalReturnTypeName})) {{ Descriptor = {method.Name}.Descriptor }},");
        }
        sb.AppendLine("        };");
        sb.AppendLine();
        sb.AppendLine("    public static global::System.Collections.Generic.IReadOnlyDictionary<string, global::NOF.Application.ServiceOperationMapping> HandlerMappings => __rpcHandlerMappings;");
        sb.AppendLine();
        sb.AppendLine("    protected override global::System.Collections.Generic.IReadOnlyDictionary<string, global::NOF.Application.ServiceOperationMapping> GetHandlerMappings()");
        sb.AppendLine("        => __rpcHandlerMappings;");
        sb.AppendLine();

        foreach (var method in serviceMethods)
        {
            if (method.Parameters.Length != 1
                || method.Parameters[0].Type is not INamedTypeSymbol requestType)
            {
                continue;
            }

            var responseType = ExpectedFailureModel.ResponseTypeName(method, classSymbol);
            var requestTypeName = requestType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

            var failureDeclarations = ExpectedFailureModel.Declarations(method);
            var operationBase = $"global::NOF.Application.ServiceOperation<{requestTypeName}, {responseType}>";
            sb.AppendLine($"    public abstract class {method.Name} : {operationBase}, global::NOF.Application.IServiceOperationDefinition");
            sb.AppendLine("    {");
            var serviceTypeName = serviceInterface.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var allowNull = ExpectedFailureModel.AllowsNull(method);
            if (allowNull)
            {
                sb.AppendLine("        public override bool AllowsNullResponse => true;");
            }
            if (failureDeclarations.Length > 0)
            {
                FailureCaseEmitter.EmitMembers(sb, method, ExpectedFailureModel.OperationTypeName(method, classSymbol));
            }
            sb.AppendLine("        /// <summary>Gets this application's descriptor with its complete response type.</summary>");
            var caseCatalog = new StringBuilder();
            caseCatalog.Append('[');
            var businessCases = BusinessCaseTypes(method.ReturnType);
            foreach (var businessCase in businessCases)
            {
                if (caseCatalog.Length > 1)
                { caseCatalog.Append(", "); }
                var isFailure = businessCase.AllInterfaces.Any(type => type.ToDisplayString() == "NOF.Abstraction.IFailure");
                caseCatalog.Append("new(typeof(").Append(businessCase.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).Append(')');
                if (isFailure)
                { caseCatalog.Append(", true"); }
                caseCatalog.Append(')');
            }
            foreach (var failure in failureDeclarations)
            {
                var caseName = ExpectedFailureModel.CaseName(failure);
                caseCatalog.Append(", new(typeof(").Append(caseName).Append("), true, ").Append(SymbolDisplay.FormatLiteral(caseName, true)).Append(')');
            }
            caseCatalog.Append(']');
            sb.AppendLine($"        public static global::NOF.Application.ServiceOperationDescriptor<{requestTypeName}, {responseType}> Descriptor {{ get; }} = new(typeof({serviceTypeName}), nameof({serviceTypeName}.{method.Name}), allowsNullResponse: {(allowNull ? "true" : "false")}, resultCases: {caseCatalog});");
            sb.AppendLine("        static global::NOF.Application.ServiceOperationDescriptor global::NOF.Application.IServiceOperationDefinition.Descriptor => Descriptor;");
            sb.AppendLine("        /// <summary>Provides this operation's static type arguments to an adapter.</summary>");
            sb.AppendLine("        public static TResult Describe<TResult>(global::NOF.Application.IServiceOperationDescriptorVisitor<TResult> visitor) => visitor.Visit(Descriptor);");
            sb.AppendLine("        /// <summary>Invokes this server operation through the configured application pipelines.</summary>");
            sb.AppendLine($"        public static async global::System.Threading.Tasks.Task<object?> InvokeAsync(");
            sb.AppendLine($"            global::System.IServiceProvider services, {requestTypeName} request, global::NOF.Abstraction.Context context,");
            sb.AppendLine("            global::System.Threading.CancellationToken cancellationToken = default)");
            sb.AppendLine("        {");
            sb.AppendLine("            global::System.ArgumentNullException.ThrowIfNull(services);");
            sb.AppendLine("            var invoker = global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<global::NOF.Application.IOperationInvoker>(services);");
            sb.AppendLine($"            var execution = await invoker.InvokeAsync(Descriptor, request, context, cancellationToken).ConfigureAwait(false);");
            sb.AppendLine("            return execution;");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        sb.AppendLine("}");

        if (!string.IsNullOrWhiteSpace(ns))
        {
            sb.AppendLine("}");
        }

        context.AddSource($"{classSymbol.ToDisplayString().Replace('.', '_')}.ApplicationService.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static ITypeSymbol[] BusinessCaseTypes(ITypeSymbol type)
    {
        var union = type.GetAttributes().Any(attribute => attribute.AttributeClass?.ToDisplayString() == "System.Runtime.CompilerServices.UnionAttribute")
            || type.DeclaringSyntaxReferences.Any(reference => reference.GetSyntax().Kind().ToString() == "UnionDeclaration");
        if (union)
        {
            var cases = type.GetMembers().OfType<IMethodSymbol>().Where(method => method.Parameters.Length == 1
                && (method.MethodKind == MethodKind.Constructor || method.MethodKind == MethodKind.Conversion && SymbolEqualityComparer.Default.Equals(method.ReturnType, type)))
                .Select(method => method.Parameters[0].Type).Distinct(SymbolEqualityComparer.Default).OfType<ITypeSymbol>().ToArray();
            if (cases.Length > 0)
            { return cases; }
        }
        return [type];
    }

}

[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class ApplicationServiceAnalyzer : DiagnosticAnalyzer
{
    public static readonly DiagnosticDescriptor ApplicationServiceMustBePartial = new(
        "NOF300",
        "RPC server class must be partial",
        "Class '{0}' inheriting ApplicationService<TService> must be declared partial",
        "ApplicationService",
        DiagnosticSeverity.Error,
        true);

    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics =>
    [
        ApplicationServiceMustBePartial
    ];

    public override void Initialize(AnalysisContext context)
    {
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.None);
        context.EnableConcurrentExecution();
        context.RegisterSymbolAction(AnalyzeNamedType, SymbolKind.NamedType);
    }

    private static void AnalyzeNamedType(SymbolAnalysisContext context)
    {
        var type = (INamedTypeSymbol)context.Symbol;
        if (type.TypeKind != TypeKind.Class || !ApplicationServiceSymbolHelper.TryGetServiceInterface(type, out _))
        {
            return;
        }

        var location = type.Locations.FirstOrDefault() ?? Location.None;
        var isPartial = type.DeclaringSyntaxReferences
            .Select(r => r.GetSyntax())
            .OfType<ClassDeclarationSyntax>()
            .Any(c => c.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword)));
        if (!isPartial)
        {
            context.ReportDiagnostic(Diagnostic.Create(ApplicationServiceMustBePartial, location, type.Name));
        }
    }
}
