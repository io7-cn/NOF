using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System.Linq;
using System.Text;

namespace NOF.Domain.SourceGenerator;

/// <summary>Generates aggregate-owned collection views and ORM field association metadata.</summary>
[Generator]
public sealed class ReadOnlyCollectionGenerator : IIncrementalGenerator
{
    /// <summary>Reports fields or names incompatible with the collection view contract.</summary>
    public static readonly DiagnosticDescriptor InvalidField = new("NOF020", "Invalid read-only collection declaration", "{0}", "DomainCollections", DiagnosticSeverity.Error, true);
    /// <summary>Requests partial declarations so the generated public view can be added.</summary>
    public static readonly DiagnosticDescriptor RequiresPartial = new("NOF021", "Collection owner must be partial", "Collection owner '{0}' must be partial", "DomainCollections", DiagnosticSeverity.Error, true);

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var fields = context.SyntaxProvider.ForAttributeWithMetadataName("NOF.Domain.ReadOnlyCollectionAttribute",
            static (node, _) => node is VariableDeclaratorSyntax,
            static (syntax, _) => (IFieldSymbol)syntax.TargetSymbol).Collect();
        context.RegisterSourceOutput(fields, static (output, candidates) =>
        {
            foreach (var group in candidates.GroupBy(field => field.ContainingType, SymbolEqualityComparer.Default))
            {
                var owner = (INamedTypeSymbol)group.Key!;
                if (owner.ContainingType != null || owner.Arity != 0 || owner.IsRecord || owner.TypeKind != TypeKind.Class)
                {
                    output.ReportDiagnostic(Diagnostic.Create(InvalidField, owner.Locations.FirstOrDefault(), "Collection owners must be top-level non-generic classes."));
                    continue;
                }
                var nonPartial = owner.DeclaringSyntaxReferences.Select(reference => reference.GetSyntax()).OfType<ClassDeclarationSyntax>()
                    .Where(syntax => !syntax.Modifiers.Any(SyntaxKind.PartialKeyword)).ToArray();
                if (nonPartial.Length > 0)
                {
                    foreach (var declaration in nonPartial)
                    {
                        output.ReportDiagnostic(Diagnostic.Create(RequiresPartial, declaration.Identifier.GetLocation(), owner.Name));
                    }
                    continue;
                }
                var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
                if (!owner.ContainingNamespace.IsGlobalNamespace)
                {
                    source.Append("namespace ").Append(owner.ContainingNamespace.ToDisplayString()).AppendLine(";");
                }
                source.Append("partial class @").Append(owner.Name).AppendLine("\n{");
                var names = new System.Collections.Generic.HashSet<string>(owner.GetMembers().Select(member => member.Name));
                foreach (var field in group)
                {
                    var attribute = field.GetAttributes().First(data => data.AttributeClass?.ToDisplayString() == "NOF.Domain.ReadOnlyCollectionAttribute");
                    var fieldName = field.Name.TrimStart('_');
                    var name = attribute.ConstructorArguments.FirstOrDefault().Value as string
                        ?? (fieldName.Length == 0 ? "" : char.ToUpperInvariant(fieldName[0]) + fieldName.Substring(1));
                    var cache = "__nofReadOnly" + name;
                    if (field.IsStatic || field.DeclaredAccessibility != Accessibility.Private || !field.IsReadOnly
                        || field.Type is not INamedTypeSymbol { TypeArguments.Length: 1 } collection
                        || collection.OriginalDefinition.ToDisplayString() is not ("System.Collections.Generic.List<T>" or "System.Collections.Generic.HashSet<T>")
                        || !SyntaxFacts.IsValidIdentifier(name) || SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None
                        || !names.Add(name) || !names.Add(cache))
                    {
                        output.ReportDiagnostic(Diagnostic.Create(InvalidField, field.Locations.FirstOrDefault(), "Use a private readonly List<T> or HashSet<T> and a unique valid property name."));
                        continue;
                    }
                    var element = collection.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                    source.Append("    private global::NOF.Domain.ReadOnlyCollectionView<").Append(element).Append(">? ").Append(cache).AppendLine(";");
                    source.AppendLine("    /// <summary>Gets the live read-only collection owned by this aggregate.</summary>");
                    source.Append("    [global::NOF.Domain.CollectionBackingField(nameof(@").Append(field.Name).AppendLine("))]");
                    source.Append("    public global::System.Collections.Generic.IReadOnlyCollection<").Append(element).Append("> ").Append(name)
                        .Append(" => ").Append(cache).Append(" ?? global::System.Threading.Interlocked.CompareExchange(ref ").Append(cache)
                        .Append(", new global::NOF.Domain.ReadOnlyCollectionView<").Append(element).Append(">(@").Append(field.Name).Append("), null) ?? ")
                        .Append(cache).AppendLine("!;");
                }
                source.AppendLine("}");
                output.AddSource(owner.ToDisplayString().Replace('.', '_') + ".ReadOnlyCollections.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
            }
        });
    }
}
